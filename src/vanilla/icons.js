export function renderIcon(name, className = 'w-4 h-4', extraAttrs = '') {
  if (!name) return '';
  const key = name in iconNodes ? name : (name.toLowerCase() in iconNodes ? name.toLowerCase() : null);
  const node = key ? iconNodes[key] : null;
  if (!node) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${className}" ${extraAttrs}><circle cx="12" cy="12" r="10"></circle><line x1="12" y1="8" x2="12" y2="12"></line><line x1="12" y1="16" x2="12.01" y2="16"></line></svg>`;
  }
  const children = node.map(([tag, attrs]) => {
    const attrPairs = Object.entries(attrs)
      .filter(([k]) => k !== 'key')
      .map(([k, v]) => `${k}="${v}"`)
      .join(' ');
    return `<${tag} ${attrPairs}></${tag}>`;
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${className}" ${extraAttrs}>${children}</svg>`;
}

